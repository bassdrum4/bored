#!/usr/bin/env node
// Rebuild src/changelog-data.js from the repository's own history, so the
// changelog page lists what actually reached main instead of a hand-kept list.
// Run it after pulling or pushing: npm run changelog
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'https://github.com/bassdrum4/bored';
const FIELD = '\x1f';

const raw = execFileSync('git', [
  'log', 'HEAD', '--no-merges', '--date=short',
  `--format=%h${FIELD}%ad${FIELD}%an${FIELD}%s`
], { cwd: root, encoding: 'utf8' });

const entries = raw.split('\n').filter(Boolean).map(line => {
  const [sha, date, author, subject] = line.split(FIELD);
  // A squash-merged branch keeps its pull request number at the end of the
  // subject; lift it out so the page can link the discussion.
  const merged = /\(#(\d+)\)\s*$/.exec(subject || '');
  const entry = { sha, date, author, subject: (subject || '').replace(/\(#\d+\)\s*$/, '').trim() };
  if (merged) entry.pr = Number(merged[1]);
  return entry;
});

if (entries.length === 0) {
  console.error('changelog: git log returned no commits');
  process.exit(1);
}

// git orders by history, not by date: a rebased commit can sit between two
// older ones, which would break the page's day grouping. Sorting by date here
// keeps a day together and leaves git's order inside the day untouched.
entries.sort((a, b) => (a.date === b.date ? 0 : a.date < b.date ? 1 : -1));

const meta = {
  count: entries.length,
  newest: entries[0].date,
  oldest: entries[entries.length - 1].date,
  repo: REPO
};

const file = join(root, 'src', 'changelog-data.js');
writeFileSync(file, [
  '// Generated by scripts/changelog.mjs — do not edit by hand.',
  '// Rebuild with: npm run changelog',
  '',
  `export const CHANGELOG_META = ${JSON.stringify(meta, null, 2)};`,
  '',
  'export const CHANGELOG = [',
  entries.map(entry => '  ' + JSON.stringify(entry)).join(',\n'),
  '];',
  ''
].join('\n'));

console.log(`changelog: ${entries.length} commits (${meta.oldest} to ${meta.newest}) -> src/changelog-data.js`);
