#!/usr/bin/env node
// Ballistic Chickens is -ezbreez-'s kaboom.js game (the idea is mrVoo's), served
// at funner.global.ssl.fastly.net/games/alotmoreagain/ballisticchickens/. Its
// source is plain JavaScript, so this vendors it as-is in source/ and builds the
// arcade document by inlining it, with a short list of deliberate patches.
//
//   node src/prototypes/ballistic-chickens/build.mjs           # rebuild
//   node src/prototypes/ballistic-chickens/build.mjs --check   # verify only
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const docPath = join(here, '../../games/content/ballistic-chickens.html');
const BEGIN = '<!-- BEGIN GAME CODE (generated by src/prototypes/ballistic-chickens/build.mjs) -->';
const END = '<!-- END GAME CODE -->';

const read = (path) => readFileSync(join(here, 'source', path), 'utf8');
const must = (text, from, to, label) => {
  if (!text.includes(from)) throw new Error(`patch target missing: ${label}`);
  return text.split(from).join(to);
};

// 1. start.js: the art and fonts come from the game's own CDN, because the
//    document is served from bassdrum4.github.io and relative paths would 404.
let start = read('code/start.js');
start = must(start, "loadRoot('sprites/');", "loadRoot(BC_ASSETS + 'sprites/');", 'sprite root');
for (const font of ['rubik', 'ubuntu', 'manrope', 'burned']) {
  start = must(start, `'fonts/${font}.ttf'`, `BC_ASSETS + 'fonts/${font}.ttf'`, `font ${font}`);
}

// 2. game.js: the save record goes through the arcade's own helpers rather than
//    kaboom's getData/setData (which write the bare key "save"), publish the
//    run's numbers for the hub's snapshot, reset them when a run starts, and
//    remember the best distance in the save record.
let game = read('code/game.js');
game = must(game, "const STUFF = getData('save', {", 'const STUFF = bcLoadSave({', 'save read');
game = must(game, "setData('save', STUFF);", 'bcStoreSave(STUFF);', 'save write');
game = must(game, `  var score = 0;
  var fuel = 50 + upgradeMod(2);`, `  window.__bcRun = { distance: 0, altitude: 0, maxAltitude: 0, score: 0, ended: false };

  var score = 0;
  var fuel = 50 + upgradeMod(2);`, 'run reset');
game = must(game, `      maxAltitude = Math.max(maxAltitude, altitude);`,
  `      maxAltitude = Math.max(maxAltitude, altitude);
      window.__bcRun = { distance: distanceF, altitude, maxAltitude, score, ended: endMenuShown };`, 'run metrics');
game = must(game, `        bcStoreSave(STUFF);`, `        STUFF.best = Math.max(STUFF.best || 0, Math.floor(distanceF));
        window.__bcRun = { distance: distanceF, altitude, maxAltitude, score, ended: true };
        bcStoreSave(STUFF);`, 'end-of-run save');

// 3. shop.js: the original only writes the save when a flight ends, so buying an
//    upgrade and closing the tab lost it. Persist the purchase immediately.
let shop = read('code/shop.js');
shop = must(shop, `      STUFF.upgrades[selectedOffer]++;
      updateShop();`, `      STUFF.upgrades[selectedOffer]++;
      bcStoreSave(STUFF);
      updateShop();`, 'shop save');

// 4. menu.js: the original sends an embedded copy of the game to a new tab
//    ("OPEN"), which is exactly how it cannot run inside the arcade.
let menu = read('code/menu.js');
menu = must(menu, `      text([(window.self == window.top ? 'PLAY' : 'OPEN'), 'HELP'][i], {`,
  `      text(['PLAY', 'HELP'][i], {`, 'menu label');
menu = must(menu, `  onClick('clickable', (b) => {
    if (window.self == window.top) { 
      fadeOut();
      setTimeout(() => { 
        go(b.goTo);
      }, FADE_TIME);
      
    } else {
      window.open('https://Ballistic-Chickens.mrvoo.repl.co', '_blank');
    };
  });`, `  onClick('clickable', (b) => {
    fadeOut();
    setTimeout(() => {
      go(b.goTo);
    }, FADE_TIME);
  });`, 'menu click');

const scripts = [
  ['data.js', read('data.js')],
  ['code/start.js', start],
  ['code/game.js', game],
  ['code/shop.js', shop],
  ['code/menu.js', menu],
  ['code/achieve.js', read('code/achieve.js')]
];

const block = [BEGIN, ...scripts.map(([name, code]) =>
  `<script>\n/* ${name} */\n${code.trimEnd()}\n</script>`), END].join('\n');

const html = readFileSync(docPath, 'utf8');
const startAt = html.indexOf(BEGIN);
const endAt = html.indexOf(END);
if (startAt < 0 || endAt < 0) throw new Error('the game document has no generated block markers');

const current = html.slice(startAt, endAt + END.length);
if (process.argv.includes('--check')) {
  if (current !== block) {
    console.error('Ballistic Chickens: the document does not match source/');
    console.error('Run: node src/prototypes/ballistic-chickens/build.mjs');
    process.exit(1);
  }
  console.log('game document matches source/ (6 files inlined)');
} else {
  writeFileSync(docPath, html.slice(0, startAt) + block + html.slice(endAt + END.length));
  console.log(`inlined ${scripts.length} files into the game document`);
}
